/* Поиск в интернете: виден, только когда реально нужен; на болтовню и
   простые расчёты не запускается; «на всякий случай» — скрыто. */
import test from 'node:test';
import assert from 'node:assert/strict';

const { __search } = await import('../api/chat.js');
const d = (q, mode) => __search.decideWebSearch({ query: q, searchEnabled: mode || 'auto' });

test('болтовня, эмоции и расчёты — без поиска', () => {
  for (const q of ['Сколько будет 67+0?', 'посчитай 15% от 300', 'она идет ко мне не сдавай меня!!!!!', 'блин я на контроше и училка идет', 'Привет, как дела?', 'ну', 'сами комментарии сделай больше на 2-3 предложения', 'Создай клон майнкрафта на html+css+js', 'объясни теорему Пифагора', 'как приготовить борщ', 'почему небо голубое']) {
    assert.equal(d(q), false, q);
  }
});

test('свежие данные, сайт, неизвестное ИИ — поиск виден', () => {
  for (const q of ['какая сейчас погода в Москве', 'курс доллара', 'найди официальный сайт Яндекс Музыки', 'дай ссылку на скачивание python', 'кто такой MrBeast', 'сколько подписчиков у канала Влад А4', 'когда выйдет GTA 6', 'что случилось с Telegram сегодня', 'поищи в интернете отзывы о гитаре']) {
    assert.equal(d(q), 'visible', q);
  }
});

test('реферат, сравнение, справка — поиск скрытый', () => {
  for (const q of ['напиши реферат про Петра Первого', 'расскажи о Второй мировой войне']) {
    assert.equal(d(q), 'silent', q);
  }
});

test('кнопка «Поиск»: включена — всегда виден, выключена — никогда', () => {
  assert.equal(d('Сколько будет 2+2', 'on'), 'visible');
  assert.equal(d('курс доллара', 'off'), false);
});
